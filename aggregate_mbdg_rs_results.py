"""Strict validator and aggregator for MBDG-RS pure-LOSO folds."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

from model_names import (
    MBDG_RS_ID,
)


SUPPORTED_EXPERIMENTS = {"faceemg11_mbdg_rs_ablation_loso"}


def load_fold(path):
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    if payload.get("schema_version") != 3:
        raise ValueError("unexpected schema in %s" % path)
    if payload.get("experiment") not in SUPPORTED_EXPERIMENTS:
        raise ValueError("unexpected experiment in %s" % path)
    protocol = payload["protocol"]
    if protocol["target_samples_used_for_fit_or_selection"] != 0:
        raise ValueError("target leakage flag in %s" % path)
    if protocol["source_blocks"] != list(range(1, 31)) or protocol["target_blocks"] != list(range(1, 31)):
        raise ValueError("not full 30-block pure LOSO in %s" % path)
    if payload["counts"]["source_trials"] != 3630 or payload["counts"]["target_trials"] != 330:
        raise ValueError("trial count mismatch in %s" % path)
    return payload


def validate_method(row, expected=330):
    if row["n_test_trials"] != expected:
        raise ValueError("unexpected trial count")
    if len(row["truth"]) != expected or len(row["prediction"]) != expected:
        raise ValueError("missing trial-level predictions")


def summarize_rows(rows):
    values = np.asarray([row["accuracy"] for row in rows], dtype=float)
    f1 = np.asarray([row["macro_f1"] for row in rows], dtype=float)
    return {
        "participant_macro_accuracy": float(values.mean()),
        "participant_sd_accuracy": float(values.std(ddof=1)),
        "participant_macro_f1": float(f1.mean()),
        "participant_sd_macro_f1": float(f1.std(ddof=1)),
        "per_subject_accuracy": values.tolist(),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    paths = sorted(args.input.glob("fold_[0-9][0-9].json"))
    if len(paths) != 12:
        raise ValueError("expected exactly 12 completed fold JSONs, found %d" % len(paths))
    folds = [load_fold(path) for path in paths]
    targets = [fold["protocol"]["outer_target"] for fold in folds]
    if len(set(targets)) != 12:
        raise ValueError("outer targets are not unique")
    script_hashes = {fold["script_sha256"] for fold in folds}
    if len(script_hashes) != 1:
        raise ValueError("folds were not generated by one script hash")

    fixed = {}
    for name in folds[0]["fixed_1p5s_ablation"]["methods"]:
        rows = [fold["fixed_1p5s_ablation"]["methods"][name] for fold in folds]
        for row in rows:
            validate_method(row)
        fixed[name] = summarize_rows(rows)

    duration = {}
    for value in folds[0].get("observation_duration_sensitivity", {}).get("methods", {}).get(MBDG_RS_ID, {}):
        rows = [fold["observation_duration_sensitivity"]["methods"][MBDG_RS_ID][value] for fold in folds]
        for row in rows:
            validate_method(row)
        duration[value] = summarize_rows(rows)

    channel = {}
    for value in folds[0].get("channel_budget_sensitivity", {}).get("methods", {}).get(MBDG_RS_ID, {}):
        rows = [fold["channel_budget_sensitivity"]["methods"][MBDG_RS_ID][value] for fold in folds]
        for row in rows:
            validate_method(row)
        channel[value] = summarize_rows(rows)

    scale = {}
    for sigma in folds[0]["scale_robustness"]["rows"]:
        methods = {}
        for name in folds[0]["scale_robustness"]["rows"][sigma]["methods"]:
            rows = [fold["scale_robustness"]["rows"][sigma]["methods"][name] for fold in folds]
            for row in rows:
                validate_method(row)
            methods[name] = summarize_rows(rows)
        scale[sigma] = {
            "seeds": [fold["scale_robustness"]["rows"][sigma]["seed"] for fold in folds],
            "gain_hashes": [fold["scale_robustness"]["rows"][sigma]["gain_sha256"] for fold in folds],
            "methods": methods,
        }

    result = {
        "schema_version": 2,
        "experiment": "faceemg11_mbdg_rs_ablation_aggregate",
        "method_id": MBDG_RS_ID,
        "n_folds": len(folds),
        "outer_targets": targets,
        "script_sha256": sorted(script_hashes)[0],
        "fixed_1p5s_ablation": fixed,
        "observation_duration_sensitivity": duration,
        "channel_budget_sensitivity": channel,
        "scale_robustness": scale,
        "source_fold_sha256": {
            path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in paths
        },
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, sort_keys=True), encoding="utf-8")
    print(json.dumps({
        "n_folds": len(folds),
        "targets": targets,
        "fixed": {name: row["participant_macro_accuracy"] for name, row in fixed.items()},
        "output": str(args.output),
    }, indent=2))


if __name__ == "__main__":
    main()
